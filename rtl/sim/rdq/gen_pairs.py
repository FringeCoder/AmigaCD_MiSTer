#!/usr/bin/env python3
# Emit <module>_pair wrappers for tb_cpu_rdq_equiv.sv: each one takes exactly
# the port list of the current RTL module, runs the current module and the
# frozen copy (<module>_ref, in this directory) side by side on the same
# inputs, drives its outputs from the frozen copy, and raises `mism` on any
# clock where an output of the two differs. Outputs only the current module
# has (the *_n lookahead ports) come out of the current one.
#
# Generated rather than written out because the port lists are long and the
# point of the bench is that nothing is left out: a port added to the RTL and
# not to a hand-written pair would silently go uncompared.
#
#   python3 gen_pairs.py > pairs.v
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RTL = os.path.join(HERE, "..", "..")

MODULES = [
	("cpu_cache_new", os.path.join(RTL, "cpu_cache_new.v"), os.path.join(HERE, "cpu_cache_new_ref.v")),
	("sdram_ctrl",    os.path.join(RTL, "sdram_ctrl.v"),    os.path.join(HERE, "sdram_ctrl_ref.v")),
	("ddram_ctrl",    os.path.join(RTL, "ddram_ctrl.v"),    os.path.join(HERE, "ddram_ctrl_ref.v")),
]

PORT = re.compile(r"^\s*(input|output|inout)\s+(?:reg\s+|wire\s+)?(\[[^\]]+\])?\s*(\w+)\s*,?\s*$")

def ports(path, name):
	src = open(path).read()
	src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
	m = re.search(r"\bmodule\s+" + name + r"\b(.*?)\);", src, re.S)
	assert m, (path, name)
	head = m.group(1)
	params = re.findall(r"parameter\s+(\w+)\s*=\s*([^\s,)]+)", head)
	out = []
	for line in head.split("\n"):
		line = line.split("//")[0]
		if not line.strip() or line.strip() in ("(", ","):
			continue
		pm = PORT.match(line)
		if pm:
			out.append((pm.group(1), pm.group(2) or "", pm.group(3)))
	assert out, (path, "no ports parsed")
	return params, out

print("// GENERATED by gen_pairs.py -- do not edit")
print("`timescale 1ns/1ps")
for name, cur, ref in MODULES:
	params, cp = ports(cur, name)
	_, rp = ports(ref, name + "_ref")
	rnames = {p[2]: p for p in rp}
	for d, w, n in rp:
		assert n in {p[2] for p in cp}, f"{name}: port {n} only in the frozen copy"
		assert (d, w) == next((pd, pw) for pd, pw, pn in cp if pn == n), f"{name}: port {n} changed"
	shared_out = [(d, w, n) for d, w, n in cp if d != "input" and n in rnames]
	pdecl = ""
	if params:
		pdecl = " #(" + ", ".join(f"parameter {k} = {v}" for k, v in params) + ")"
	plist = ",\n\t".join(f"{d} {w} {n}".replace("  ", " ") for d, w, n in cp)
	print(f"\nmodule {name}_pair{pdecl}\n(\n\t{plist},\n\toutput mism\n);")
	for d, w, n in shared_out:
		print(f"wire {w} n_{n};")
		if d == "inout":
			# the current module's own copy of the bus: whatever the frozen
			# copy or the bench puts on the real one, overridden by its own drive
			print(f"assign (weak0, weak1) n_{n} = {n};")
	pinst = ""
	if params:
		pinst = " #(" + ", ".join(f".{k}({k})" for k, _ in params) + ")"
	print(f"{name}_ref{pinst} r (.*);")
	ov = ", ".join(f".{n}(n_{n})" for _, _, n in shared_out)
	print(f"{name}{pinst} n (.*, {ov});")
	ref_v = ", ".join(n for _, _, n in shared_out)
	new_v = ", ".join(f"n_{n}" for _, _, n in shared_out)
	print(f"assign mism = {{{ref_v}}} !== {{{new_v}}};")
	print("endmodule")
